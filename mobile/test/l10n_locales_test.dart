      final l = lookupAppLocalizations(locale);
      final bad = <String>[];
      for (final (key, must, call) in _calls) {
        final String s;
        try {
          s = call(l);
        } catch (e) {
          bad.add('$key: $e');
          continue;
        }
        if (s.trim().isEmpty) bad.add('$key: empty');
        if (s.contains('{') || s.contains('}')) bad.add('$key: brace in $s');
        for (final m in must) {
          if (!s.contains(m)) bad.add('$key: $m missing from $s');
        }
      }
      expect(bad, isEmpty);
    });
  }
}
