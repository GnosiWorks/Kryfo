#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# a windows version resource for one of the app's dlls, from fixed inputs
# only (no date, no path), so the dll can reproduce:
#   version-rc.sh <out.o> <file name> <description> <copyright> [comments]
# writes <out>.rc and the coff object <out.o> that the link takes in.
# the version is the app's, from the version: line in mobile/pubspec.yaml
# (0.6.0+12 becomes 0.6.0.12). WINDRES_W picks the windres.
set -euo pipefail
die() { echo "error: $*" >&2; exit 1; }
here=$(cd "$(dirname "$0")" && pwd)
obj="${1:?usage: version-rc.sh <out.o> <file name> <description> <copyright> [comments]}"
name="${2:?no file name}"
desc="${3:?no description}"
copy="${4:?no copyright}"
comments="${5:-}"
WINDRES_W="${WINDRES_W:-x86_64-w64-mingw32-windres}"
command -v "$WINDRES_W" >/dev/null || die "$WINDRES_W not found (mingw-w64 binutils)"
rc="${obj%.o}.rc"

v=$(sed -n 's/^version: *//p' "$here/../../mobile/pubspec.yaml" | head -1 | tr -d '\r')
[[ "$v" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)(\+([0-9]+))?$ ]] || die "pubspec version '$v' is not x.y.z+n"
n="${BASH_REMATCH[1]},${BASH_REMATCH[2]},${BASH_REMATCH[3]},${BASH_REMATCH[5]:-0}"
s="${n//,/.}"

# rc strings: no quote or backslash, so nothing needs escaping
for x in "$name" "$desc" "$copy" "$comments"; do
  [[ "$x" != *[\"\\]* ]] || die "a quote or backslash in '$x'"
done
val() { printf '      VALUE "%s", "%s"\n' "$1" "$2"; }

cat >"$rc" <<EOF
// generated by packaging/windows/version-rc.sh
1 VERSIONINFO
FILEVERSION $n
PRODUCTVERSION $n
FILEFLAGSMASK 0x3f
FILEFLAGS 0x0
FILEOS 0x40004
FILETYPE 0x2
FILESUBTYPE 0x0
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
$(val CompanyName GnosiWorks)
$(val FileDescription "$desc")
$(val FileVersion "$s")
$(val InternalName "${name%.*}")
$(val LegalCopyright "$copy")
$(val OriginalFilename "$name")
$(val ProductName Kryfo)
$(val ProductVersion "$s")
$([ -z "$comments" ] || val Comments "$comments")
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
EOF
# the rc has no #include, so the preprocessor adds nothing of its own
"$WINDRES_W" -O coff -c 65001 -i "$rc" -o "$obj"
